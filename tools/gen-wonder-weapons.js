#!/usr/bin/env node
/* Writes the WONDER_WEAPON_STAT block at the end of src/data.js from lufel.net's Wonder weapon list
 * (/data/kr/wonder/weapons.js): for each dagger, by its English name, the stats it always adds to Wonder's own
 * panel, as a 7-step refinement ladder (R0-R6) — "Increase Attack by 28.0%/32.7%/.../56.0%." The user's panel
 * (Nov 2026, docs/DATA-SOURCES.md) showed Starry Compass R6's 56% in Wonder's ATK. The dagger's flat HP, ATK and
 * DEF are not on lufel; the Weapons tab takes them from the user's own screen.
 *
 *     node tools/gen-wonder-weapons.js              # downloads lufel's weapons.js
 *     node tools/gen-wonder-weapons.js weapons.js   # or reads a saved copy
 *
 * Like gen-bosses.js it touches nothing else in the file: the block sits between two marker comments, is
 * replaced whole on a re-run (a second run is byte-identical), and is appended when the markers are absent.
 * Which sentences count is tools/wonder-self-stats.js's rule; a ladder that is not 7 long is reported and left out.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { selfStats } = require('./wonder-self-stats');

const ROOT = path.resolve(__dirname, '..');
const DATA_FILE = path.join(ROOT, 'src', 'data.js');
const BEGIN = '/* ---- WONDER_WEAPON_STAT: generated by tools/gen-wonder-weapons.js from lufel.net wonder/weapons.js — do not edit by hand ---- */';
const END = '/* ---- end WONDER_WEAPON_STAT ---- */';
const URL = 'https://lufel.net/data/kr/wonder/weapons.js';
const q = s => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";

async function main() {
  const src = process.argv[2] ? fs.readFileSync(process.argv[2], 'utf8')
    : await (await fetch(URL, { headers: { 'User-Agent': 'p5x-planner/1.0' } })).text();
  const ctx = { window: {} };
  vm.createContext(ctx);
  vm.runInContext(src, ctx);
  const list = ctx.window.matchWeapons;
  if (!list) throw new Error('no matchWeapons in lufel weapons.js');
  const warn = [];
  const rows = Object.entries(list).map(([kr, w]) => {
    const n = String(w.name_en || '').trim();
    if (!n) { warn.push('no English name: ' + kr); return null; }
    const st = selfStats(w.effect_en).filter(([k, v]) => {
      const ok = Array.isArray(v) && v.length === 7;
      if (!ok) warn.push(`${n}: ${k} is not a 7-step ladder, left out`);
      return ok;
    });
    return [n, st];
  }).filter(Boolean).sort((a, b) => a[0].localeCompare(b[0]));
  const lines = rows.map(([n, st]) => `  ${q(n)}: [${st.map(([k, v]) => `[${q(k)}, [${v.join(', ')}]]`).join(', ')}],`);
  lines[lines.length - 1] = lines[lines.length - 1].replace(/,$/, '');

  const text = fs.readFileSync(DATA_FILE, 'utf8');
  const EOL = text.includes('\r\n') ? '\r\n' : '\n';
  const block = [BEGIN,
    '/* Each Wonder dagger lufel lists, by English name: the stats it always adds to his own panel, by refinement',
    '   R0-R6 (key, ladder). Read by wonderCalc in logic.js; see tools/gen-wonder-weapons.js. */',
    'const WONDER_WEAPON_STAT = {', ...lines, '};', END].join('\n').replace(/\n/g, EOL);
  const at = text.indexOf(BEGIN);
  let res;
  if (at >= 0) {
    const endAt = text.indexOf(END, at);
    if (endAt < 0) throw new Error('WONDER_WEAPON_STAT begin marker without an end marker in src/data.js');
    res = text.slice(0, at) + block + text.slice(endAt + END.length);
  } else res = text.replace(/\s*$/, '') + EOL + EOL + block + EOL;
  fs.writeFileSync(DATA_FILE, res, 'utf8');
  warn.forEach(w => console.error('WONDER_WEAPON_STAT: ' + w));
  console.error(`WONDER_WEAPON_STAT: ${rows.length} weapons, ${rows.filter(([, st]) => st.length).length} with a panel stat`);
}

main();
