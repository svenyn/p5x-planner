#!/usr/bin/env node
/* Writes the WONDER_DMG block at the end of src/data.js from lufel.net's Persona files and Persona skill list:
 * the damage Wonder deals with each Persona's unique skill and Highlight, and with every attack skill a Persona
 * can have (innate skills, skill cards, fused skills), for the Teams tab's fight (his own hits, priced from the
 * ATK and crit the user enters for him).
 *
 *     node tools/gen-wonder-damage.js            # downloads lufel's index, the 155 Persona files and skills.js
 *     node tools/gen-wonder-damage.js <folder>   # or reads a saved index.js, <Korean name>.js files and skills.js
 *
 * Like gen-wonder-innate.js it touches nothing else in the file: the block sits between two marker comments,
 * is replaced whole on a re-run (a second run is byte-identical), and is appended when the markers are absent.
 *
 * How the text is read: lufel's English descriptions write every damaging clause as "Deal <Element> damage to
 * <1 foe | all foes> equal to a/b/c% of Attack (N hits)" — a/b/c at skill levels 6/7/8, per hit when a hit count
 * is printed. Each such clause becomes a part [element, all foes (1/0), hits, a, b, c]; a skill with two clauses
 * keeps both. A clause with one value (Gabriel's unique) is that value at every level. A clause with no number
 * ("Deal Fire damage to 1 foe.") is left out and reported. Skills are keyed by English name; an innate skill and a
 * skill card of the same name are one skill, the skill list's numbers kept when the two differ (reported).
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const DATA_FILE = path.join(ROOT, 'src', 'data.js');
const BEGIN = '/* ---- WONDER_DMG: generated by tools/gen-wonder-damage.js from lufel.net persona files and wonder/skills.js — do not edit by hand ---- */';
const END = '/* ---- end WONDER_DMG ---- */';
const BASE = 'https://lufel.net/';
const q = s => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const get = async u => {
  const r = await fetch(u, { headers: { 'User-Agent': 'p5x-planner/1.0' } });
  if (!r.ok) throw new Error(r.status + ' ' + u);
  return r.text();
};
const ELEM = { Fire: 'Fire', Ice: 'Ice', Electric: 'Electric', Wind: 'Wind', Psy: 'Psychokinesis', Psychokinesis: 'Psychokinesis', Psychokinetic: 'Psychokinesis',
  Nuclear: 'Nuclear', Bless: 'Bless', Curse: 'Curse', Almighty: 'Almighty', Physical: 'Physical', Gun: 'Gun' };
const CLAUSE = /Deal (\w+) damage (?:to ([^.]*?) )?equal to ((?:\d+(?:\.\d+)?%?\/?)+)\s+of Attack(?:\s*\((\d+) hits?\))?/g;

async function main() {
  const dir = process.argv[2];
  const ctx = { window: {} };
  vm.createContext(ctx);
  const read = async (name, sub) => dir ? fs.readFileSync(path.join(dir, name.replace(/[\\/:*?"<>|]/g, '_') + '.js'), 'utf8')
    : get(BASE + (sub || 'data/persona') + '/' + encodeURIComponent(name) + '.js');
  vm.runInContext(await read('index', 'data/persona'), ctx);
  const index = ctx.window.personaIndex;
  if (!index) throw new Error('no personaIndex in lufel index.js');
  for (const [name, e] of Object.entries(index)) vm.runInContext(await read(name, e.__path), ctx);
  vm.runInContext(dir ? fs.readFileSync(path.join(dir, 'skills.js'), 'utf8') : await get(BASE + 'data/kr/wonder/skills.js'), ctx);
  const files = ctx.window.personaFiles || {}, list = ctx.window.personaSkillList;
  if (!list) throw new Error('no personaSkillList in lufel skills.js');

  const warn = [];
  const parts = (who, text) => {
    const s = String(text || ''), out = [];
    for (const m of s.matchAll(CLAUSE)) {
      const el = ELEM[m[1]];
      if (!el) { warn.push(`${who}: element "${m[1]}" has no English name here`); continue; }
      const v = m[3].split('/').map(x => parseFloat(x)).filter(x => !isNaN(x));
      const lv = v.length === 3 ? v : v.length === 1 ? [v[0], v[0], v[0]] : null;
      if (!lv) { warn.push(`${who}: ${v.length} values in "${m[0]}"`); continue; }
      out.push([el, /all foes/i.test(m[2] || '') ? 1 : 0, m[4] ? +m[4] : 1, ...lv]);
    }
    if (!out.length && /Deal \w+ damage/.test(s)) warn.push(`${who}: a damage clause with no number, left out`);
    return out;
  };
  const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);

  // attack skills by name: the skill list first, then innate skills it does not have
  const skills = new Map();
  Object.values(list).forEach(s => {
    const n = String(s.name_en || '').trim();
    if (!n) return;
    const p = parts('skill ' + n, s.description_en);
    if (!p.length) return;
    if (skills.has(n) && !same(skills.get(n), p)) warn.push(`skill ${n}: listed twice with different damage, the first kept`);
    else skills.set(n, p);
  });
  const personas = [];
  Object.values(files).forEach(f => {
    const n = String(f.name_en || '').trim();
    if (!n) return;
    const u = parts(n + ' unique', f.uniqueSkill && f.uniqueSkill.desc_en), hl = parts(n + ' Highlight', f.highlight && f.highlight.desc_en);
    (f.innate_skill || []).forEach(s => {
      const k = String(s.name_en || '').trim(), p = parts(n + ' innate ' + k, s.desc_en);
      if (!k || !p.length) return;
      if (!skills.has(k)) skills.set(k, p);
      else if (!same(skills.get(k), p)) warn.push(`${n}: innate ${k} differs from the skill list's, the list's kept`);
    });
    if (u.length || hl.length) personas.push([n, u, hl]);
  });
  personas.sort((a, b) => a[0].localeCompare(b[0]));
  const arr = p => '[' + p.map(x => '[' + q(x[0]) + ', ' + x.slice(1).join(', ') + ']').join(', ') + ']';
  const pLines = personas.map(([n, u, hl]) => `    ${q(n)}: { ${[u.length ? 'u: ' + arr(u) : '', hl.length ? 'hl: ' + arr(hl) : ''].filter(Boolean).join(', ')} },`);
  const sLines = [...skills.entries()].sort((a, b) => a[0].localeCompare(b[0])).map(([n, p]) => `    ${q(n)}: ${arr(p)},`);
  [pLines, sLines].forEach(L => { if (L.length) L[L.length - 1] = L[L.length - 1].replace(/,$/, ''); });

  const text = fs.readFileSync(DATA_FILE, 'utf8');
  const EOL = text.includes('\r\n') ? '\r\n' : '\n';
  const block = [BEGIN,
    '/* Wonder\'s own damage (lufel\'s English Persona and skill text): each part [element, all foes (1/0), hits,',
    '   % of Attack per hit at skill levels 6/7/8]. `personas`: a Persona\'s unique skill (u) and Highlight (hl);',
    '   `skills`: every attack skill a Persona can have (innate, skill card, fused), by English name. The Teams tab\'s',
    '   fight deals these from the ATK and crit entered for him. See tools/gen-wonder-damage.js. */',
    'const WONDER_DMG = {', '  personas: {', ...pLines, '  },', '  skills: {', ...sLines, '  }', '};', END].join(EOL);
  const a = text.indexOf(BEGIN), b = text.indexOf(END);
  const next = a >= 0 && b > a ? text.slice(0, a) + block + text.slice(b + END.length) : text.replace(/\s*$/, '') + EOL + EOL + block + EOL;
  fs.writeFileSync(DATA_FILE, next);
  warn.forEach(w => console.error('WONDER_DMG: ' + w));
  console.log(`WONDER_DMG: ${personas.length} Personas, ${skills.size} attack skills`);
}
main().catch(e => { console.error(e); process.exit(1); });
