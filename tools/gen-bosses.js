#!/usr/bin/env node
/* Writes the BOSSES block at the end of src/data.js from lufel.net's defence calculator boss list
 * (/data/kr/calc/boss.js): each boss's base DEF, DEF coefficient and element resistances. The Teams
 * tab's fight takes its target from it.
 *
 *     node tools/gen-bosses.js            # downloads lufel's boss.js
 *     node tools/gen-bosses.js boss.js    # or reads a saved copy
 *
 * Like gen-teams.js it touches nothing else in the file: the block sits between two marker
 * comments, is replaced whole on a re-run (a second run is byte-identical), and is appended when
 * the markers are absent.
 *
 * How lufel's file is read:
 *   baseDefense   the boss's DEF;  defenseCoef  its DEF coefficient as a percentage of base
 *                 (258.4 is +158.4%, the article's Vishnu: TC_BOSS's `coef` 1.584);
 *   resistances   per element, "약" weak, "내" resist, anything else normal; a boss with none listed
 *                 has no resistance data and the fight takes every hit as a weakness hit;
 *   isSea         Sea of Souls content (the rest is other boss content).
 * Names: lufel's English where it has one, else NAME_EN below (the demons' usual English names),
 * else the Korean name as it is, reported on stderr.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const DATA_FILE = path.join(ROOT, 'src', 'data.js');
const BEGIN = '/* ---- BOSSES: generated by tools/gen-bosses.js from lufel.net calc/boss.js — do not edit by hand ---- */';
const END = '/* ---- end BOSSES ---- */';
const URL = 'https://lufel.net/data/kr/calc/boss.js';
const q = s => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";

const NAME_EN = {
  '바포멧': 'Baphomet', '쿠 훌린': 'Cu Chulainn', '오베론': 'Oberon', '티타니아': 'Titania', '도미니온': 'Dominion',
  '수르트': 'Surt', '비사문천': 'Bishamonten', '광목천': 'Koumokuten', '증장천': 'Zouchouten', '지국천': 'Jikokuten',
  '멜키세덱': 'Melchizedek', '청룡': 'Seiryu', '비슈누': 'Vishnu', '화신': 'Avatar', '바알': 'Baal', '위타천': 'Kartikeya',
  '가루다': 'Garuda', '자타유': 'Jatayu', '호루스': 'Horus', '야타가라스': 'Yatagarasu', '마라': 'Mara', '데카라비아': 'Decarabia',
  '잭 오 랜턴': "Jack-o'-Lantern", '아크엔젤': 'Archangel', '프린시펄리티': 'Principality', '파워': 'Power', '엔젤': 'Angel',
  '니드호그': 'Nidhoggr', '유룽': 'Yurlungur', '파프니르': 'Fafnir', '아타바크': 'Atabaka', '야츠후사': 'Yatsufusa',
  '야츠카미즈오미츠누': 'Yatsukamizu Omitsunu'
};
const ELEMENT = { physics: 'Physical', shoot: 'Gun', fire: 'Fire', ice: 'Ice', electric: 'Electric', wind: 'Wind', think: 'Psychokinesis', pit: 'Nuclear', blessing: 'Bless', curse: 'Curse' };

async function main() {
  const src = process.argv[2] ? fs.readFileSync(process.argv[2], 'utf8')
    : await (await fetch(URL, { headers: { 'User-Agent': 'p5x-planner/1.0' } })).text();
  const ctx = vm.createContext({});
  vm.runInContext(src.replace(/^(\s*)(?:const|let)\s+/gm, '$1var '), ctx);
  if (!Array.isArray(ctx.bossData)) throw new Error('no bossData in lufel boss.js');

  const warn = new Set();
  // lufel's English where it has one, part by part ("Kartikeya / 가루다" still needs its second half)
  const nameOf = b => {
    return String(b.name_en || b.name).split(' / ').map(p => {
      const t = p.trim();
      if (NAME_EN[t]) return NAME_EN[t];
      if (/[가-힣]/.test(t)) warn.add('no English name: ' + t);
      return t;
    }).join(' / ');
  };
  const lines = ctx.bossData.map(b => {
    const res = {};
    Object.entries(b.resistances || {}).forEach(([k, v]) => { if (ELEMENT[k] && (v === '약' || v === '내')) res[ELEMENT[k]] = v === '약' ? 'weak' : 'resist'; });
    const known = b.resistances && Object.keys(b.resistances).length > 0;
    const bits = [`id:${+b.id}`, `name:${q(nameOf(b))}`, `sea:${!!b.isSea}`, `def:${+b.baseDefense}`, `coef:${Math.round((+b.defenseCoef - 100) * 10) / 1000}`];
    if (known) bits.push(`res:{${Object.entries(res).map(([k, v]) => `${k}:${q(v)}`).join(',')}}`);
    return `  { ${bits.join(', ')} },`;
  });

  const text = fs.readFileSync(DATA_FILE, 'utf8');
  const EOL = text.includes('\r\n') ? '\r\n' : '\n';
  const block = [BEGIN,
    '/* lufel\'s defence-calculator bosses: base DEF (`def`), DEF coefficient over base (`coef`, 1.584 = +158.4%),',
    '   Sea of Souls or not (`sea`), and element resistances where lufel lists them (`res`: weak / resist, the',
    '   rest normal). The Teams tab\'s fight is against the one the page picks. See tools/gen-bosses.js. */',
    'const BOSSES = [', ...lines, '];', END].join('\n').replace(/\n/g, EOL);
  const at = text.indexOf(BEGIN);
  let out;
  if (at >= 0) {
    const endAt = text.indexOf(END, at);
    if (endAt < 0) throw new Error('BOSSES begin marker without an end marker in src/data.js');
    out = text.slice(0, at) + block + text.slice(endAt + END.length);
  } else out = text.replace(/\s*$/, '') + EOL + EOL + block + EOL;
  fs.writeFileSync(DATA_FILE, out, 'utf8');
  console.error(`BOSSES: ${lines.length} bosses`);
  for (const w of warn) console.error('  ! ' + w);
}

main();
