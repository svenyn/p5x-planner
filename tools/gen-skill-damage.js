#!/usr/bin/env node
/* Writes the SKILL_DMG block at the end of src/data.js from lufel.net's per-character skill.js
 * files: how much damage each of a character's three skills and their Highlight (or Theurgy)
 * deals, as a percentage of the stat it scales with. The Teams tab's calculated basis reads it
 * for one thing only — what share of a damage dealer's own damage lands on their Highlight —
 * so that a buff to Highlight damage, a Highlight cast early or an extra Highlight can be priced.
 *
 *     node tools/fetch-lufel-data.js lufel.json
 *     node tools/gen-skill-damage.js lufel.json   # replaces the SKILL_DMG block in place
 *
 * Like gen-teams.js it touches nothing else in the file: the block sits between two marker
 * comments, is replaced whole on a re-run (a second run is byte-identical), and is appended
 * when the markers are absent.
 *
 * How the text is read (lufel's English skill descriptions):
 *   - every "equal to X%/…% (of) [someone's] Attack | Defense | max HP" in a sentence that deals
 *     damage counts, at its first (base-level) number; "(N hits)" or "N times" right after it
 *     multiplies it. Several damage clauses in one skill add up, conditional ones included —
 *     the same rule for the skills and the Highlight, so their ratio is what is kept honest.
 *   - healing, shields and buffs worded "of Attack" are not damage and are skipped.
 *   - `hl` is 'TH' when the Highlight text names a Theurgy gauge (S.E.E.S.), else 'HL'.
 *     Elucidators have no Highlight of their own (theirs is the stat share) and get no entry.
 *   - `cd` is lufel's Highlight cooldown in turns, when it publishes one (4 for every thief).
 * Rotation turns that are not a numbered skill (Gunshot, Melee, Transform, items) are not
 * priced at all, so for those kits the Highlight's share reads a little high.
 *
 * It is an estimate of one ratio per character, not a damage model; an entry the text gets
 * wrong goes in FIXES below with its reason, never as a hand edit to the block.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const DATA_FILE = path.join(ROOT, 'src', 'data.js');
const BEGIN = '/* ---- SKILL_DMG: generated by tools/gen-skill-damage.js from lufel.net skill.js — do not edit by hand ---- */';
const END = '/* ---- end SKILL_DMG ---- */';
const q = s => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";

/* Hand corrections: [skill 1, skill 2, skill 3, Highlight] in place of what the text gives,
   each with the reason. Printed on stderr when applied. */
const FIXES = {
  'Justine & Caroline': { d: [149, 149, 149, 488], why: 'the Highlight text lists one Highlight per Persona set and she casts one; Absurdity & Nonsense (244% x2) is the damaging one of the Strategist pair the Teams tab assumes' },
  'Kotone Montagne [Frostgale]': { d: [374.1, 177.7, 527.4, 637.5], why: 'the Highlight text gives a Spring and a Winter version and she casts one: Spring, 212.5% x3' },
  'Makoto Niijima': { d: [178.7, 0, 527.4, 468.5], why: 'Sanctioned Drift\'s 5 hits fall to 20% after the first on the same target: 83 + 4 x 16.6, plus the 29.3% Technical bonus, on one boss' }
};

const SLOTS = ['skill1', 'skill2', 'skill3', 'skill_highlight'];
const STAT = /(Attack|Defense|max HP|Max HP)/;

function damageOf(text) {
  let total = 0;
  for (const sent of String(text || '').split(/(?<=\.)\s+|\n/)) {
    if (!/damage/i.test(sent)) continue;
    // a heal, shield or buff sentence that merely mentions damage elsewhere is not a hit
    if (!/\bdeal|\bdamage (?:equal|of)|damage to/i.test(sent)) continue;
    const re = /equal (?:to|of) ([\d.]+)%(?:\/[\d.]+%)*\s+(?:of\s+)?([^.,(%]*?)(Attack|Defense|max HP|Max HP)/gi;
    let m;
    while ((m = re.exec(sent))) {
      const after = sent.slice(m.index + m[0].length, m.index + m[0].length + 40);
      const hit = after.match(/^\s*\((\d+) hits?\)/) || after.match(/^[^.]{0,20}?\b(\d+) times\b/);
      const n = hit && !/up to/i.test(after.slice(0, hit.index + hit[0].length)) ? +hit[1] : 1;
      total += +m[1] * n;
    }
  }
  return Math.round(total * 10) / 10;
}

function main() {
  const lufelFile = process.argv[2] || 'lufel.json';
  const d = JSON.parse(fs.readFileSync(lufelFile, 'utf8'));
  if (!d.skills) throw new Error('lufel dump has no `skills` — re-run tools/fetch-lufel-data.js');

  const text = fs.readFileSync(DATA_FILE, 'utf8');
  const EOL = text.includes('\r\n') ? '\r\n' : '\n';
  const at = text.indexOf(BEGIN);
  const before = at >= 0 ? text.slice(0, at) : text;
  const ctx = vm.createContext({});
  vm.runInContext(before.replace(/^(\s*)(?:const|let)\s+/gm, '$1var '), ctx);
  const chars = ctx.CHARACTERS, teams = ctx.TEAMS;

  const lines = [], warn = [];
  for (const c of chars) {
    if (c.arch === 'Navigator') continue;
    const kr = (teams[c.n] || {}).kr;
    const o = kr && d.skills[kr];
    if (!o) { warn.push(`no lufel skill file: ${c.n}`); continue; }
    const en = o.en && o.en.skill1 ? o.en : ((o.enCharacterSkillsData || {})[kr] || Object.values(o.enCharacterSkillsData || {})[0]);
    if (!en) { warn.push(`no English skill text: ${c.n}`); continue; }
    const hlText = (en.skill_highlight || {}).description || '';
    let dmg = SLOTS.map(k => damageOf((en[k] || {}).description));
    if (FIXES[c.n]) { console.error(`  fix ${c.n}: ${JSON.stringify(dmg)} -> ${JSON.stringify(FIXES[c.n].d)} (${FIXES[c.n].why})`); dmg = FIXES[c.n].d; }
    const kind = /Theurgy/i.test(hlText) ? 'TH' : 'HL';
    const cool = +(en.skill_highlight || {}).cool || +((o.kr || {}).skill_highlight || {}).cool || 0;
    const bits = [`hl:${q(kind)}`];
    if (cool > 0) bits.push(`cd:${cool}`);
    bits.push(`d:[${dmg.join(',')}]`);
    lines.push(`  ${q(c.n)}: { ${bits.join(', ')} },`);
    if (!STAT.test(hlText) && dmg[3] === 0 && dmg.some(x => x > 0)) warn.push(`Highlight deals no damage by its text: ${c.n}`);
  }

  const block = [BEGIN,
    '/* Damage per use of skills 1-3 and the Highlight/Theurgy (`d`, % of the stat the kit scales with, base',
    '   skill level, hits added up), whether the character has a Highlight or a Theurgy (`hl`), and lufel\'s',
    '   Highlight cooldown in turns (`cd`). The Teams tab reads only the ratio between them: the share of a',
    '   damage dealer\'s own damage that lands on their Highlight. See tools/gen-skill-damage.js. */',
    'const SKILL_DMG = {', ...lines, '};', END].join('\n').replace(/\n/g, EOL);

  let out;
  if (at >= 0) {
    const endAt = text.indexOf(END, at);
    if (endAt < 0) throw new Error('SKILL_DMG begin marker without an end marker in src/data.js');
    out = text.slice(0, at) + block + text.slice(endAt + END.length);
  } else {
    out = text.replace(/\s*$/, '') + EOL + EOL + block + EOL;
  }
  fs.writeFileSync(DATA_FILE, out, 'utf8');
  console.error(`SKILL_DMG: ${lines.length} characters`);
  for (const w of warn) console.error('  ! ' + w);
}

main();
