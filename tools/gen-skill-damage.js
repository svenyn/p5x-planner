/* Writes the SKILL_DMG block at the end of src/data.js from lufel.net's per-character skill.js
 * files: how much damage each of a character's three skills and their Highlight (or Theurgy)
 * deals, as a percentage of the stat it scales with. The Teams tab's calculated basis reads it
 * for one thing only — what share of a damage dealer's own damage lands on their Highlight —
 * so that a buff to Highlight damage, a Highlight cast early or an extra Highlight can be priced.
 *
 *     node tools/fetch-lufel-data.js lufel.json
 *     node tools/gen-skill-damage.js lufel.json   # replaces the SKILL_DMG block in place
 *
 * Like gen-teams.js it touches nothing else in the file: the block sits between two marker
 * comments, is replaced whole on a re-run (a second run is byte-identical), and is appended
 * when the markers are absent.
 *
 * How the text is read (lufel's English skill descriptions):
 *   - every "equal to X%/…% (of) [someone's] Attack | Defense | max HP" in a sentence that deals
 *     damage counts, at its first (base-level) number; "(N hits)" or "N times" right after it
 *     multiplies it. Several damage clauses in one skill add up, conditional ones included —
 *     the same rule for the skills and the Highlight, so their ratio is what is kept honest.
 *   - healing, shields and buffs worded "of Attack" are not damage and are skipped.
 *   - `hl` is 'TH' when the Highlight text names a Theurgy gauge (S.E.E.S.), else 'HL'.
 *     Elucidators have no Highlight of their own (theirs is the stat share) and get no entry.
 *   - `cd` is lufel's Highlight cooldown in turns, when it publishes one (4 for every thief).
 * Rotation turns that are not a numbered skill (Gunshot, Melee, Transform, items) are not
 * priced at all, so for those kits the Highlight's share reads a little high.
 *
 * It is an estimate of one ratio per character, not a damage model; an entry the text gets
 * wrong goes in FIXES below with its reason, never as a hand edit to the block.
 */
