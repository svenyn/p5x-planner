#!/usr/bin/env node
/* Writes the TEAMS block at the end of src/data.js from lufel.net's per-character party.js
 * and operation.js files — the Teams tab's recommended parties, synergy partners and skill
 * rotations.
 *
 *     node tools/fetch-lufel-data.js lufel.json   # must include party.js / operation.js
 *     node tools/gen-teams.js lufel.json          # replaces the TEAMS block in place
 *
 * Like gen-awareness.js this touches nothing else in the file: the block sits between two
 * marker comments, is replaced whole on a re-run (a second run is byte-identical), and is
 * appended when the markers are absent.
 *
 * What lufel publishes, and how it is read:
 *
 *   party.js  `party`    teams of 3 thieves + the Elucidator, in no fixed order (Manaka's and
 *                        Futaba's files list the Elucidator first). Wonder joins every party
 *                        and is left out, except where a team runs him as a damage dealer.
 *                        A 5th member appears only beside Fuuka: the backup her Oracle Shift
 *                        swaps in. An empty name is a free slot. A few files carry only an
 *                        all-empty placeholder party, which is dropped.
 *             `friends`  synergy partners, each with lufel's one-line reason (comment_en) and,
 *                        for some, the Awareness level the reason needs (`A`). On Fuuka's page
 *                        these are her recommended backup characters.
 *   operation.js `basic` skill rotations, one per Awareness level and situation. Two shapes:
 *                        a line ("1 › 3 › 1 › 2+3") or a turn grid (Kotone's, with buff rows,
 *                        which are left out). `note_en` explains the kit-specific tokens.
 *
 * Everything is written in English. Labels and the few Korean skill tokens are translated by
 * the tables below; anything they do not cover is printed on stderr and kept as it is, so a
 * new kit's token shows up on the next refresh instead of vanishing. Korean-only notes are
 * reported and skipped rather than machine-translated.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const DATA_FILE = path.join(ROOT, 'src', 'data.js');
const BEGIN = '/* ---- TEAMS: generated by tools/gen-teams.js from lufel.net party.js / operation.js — do not edit by hand ---- */';
const END = '/* ---- end TEAMS ---- */';

const q = s => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")
  .replace(/\r\n|\r|\n/g, '\\n') + "'";

/* Same matching as gen-awareness.js (itself a copy of gen-data-from-lufel.js's). */
const EXPLICIT = {
  'NAVI': 'Futaba Sakura', 'MAKOTO': 'Makoto Yuki', 'QUEEN': 'Makoto Niijima',
  'AEGIS': 'Aigis', 'FUKA': 'Fuuka Yamagishi', 'KIRIJO': 'Mitsuru Kirijo',
  'AKIHIKO': 'Akihiko Sanada', 'YUKARI': 'Yukari Takeba', 'JUNPEI': 'Junpei Iori',
  'KOROMARU': 'Koromaru', 'J&C': 'Justine & Caroline', 'BUI': 'YUI',
  'MONT': 'Kotone Montagne', 'MONT·Frostgale': 'Kotone Montagne [Frostgale]',
  'BUI·Prism': 'YUI [Prism]', 'BUI·Cosmic': 'YUI [Prism]',
  'CHORD·Summer': 'Ayaka Sakai [Summer]', 'BERRY·Summer': 'Ichigo Shikano [Summer]', 'CLOSER·Tropical': 'Motoha Arai [Tropical]',
  'CLOSER·Radiance': 'Motoha Arai [Radiance]', 'MOKO·Seaside': 'Tomoko Noge [Seaside]',
  // lufel renamed these two by Nov 22 2026 (name_en "Gunslinger Shun", "Tenebre Shoki"); without them a re-run drops their teams
  'SOY·Gunslinger': 'Shun Kano [Pioneer]', 'LUCE·Tenebre': 'Shoki Ikenami [Notte]',
  'MARIAN·Beachflower': 'Minami Miyashita [Beachflower]',
  'PUPPET·Wavecatcher': 'Miyu Sahara [Wavecatcher]', 'WIND·Tempest': 'Riko Tanemura [Tempest]',
  'RIN·Firecracker': 'Yaoling Li [Firecracker]', 'LUCE·Notte': 'Shoki Ikenami [Notte]',
  'SOY·Pioneer': 'Shun Kano [Pioneer]', 'JOKER·Starlight': 'Ren Amamiya [Starlight]',
  'MONA·Starlight': 'Morgana [Starlight]', 'PANTHER·Starlight': 'Ann Takamaki [Starlight]'
};
const norm = n => String(n).replace(/[^a-z]/gi, '').toLowerCase();
/* The player character: in no gacha roster, in every party. lufel names him only where a team
   builds him as the damage dealer. */
const WONDER_KR = '원더';

/* Rotation labels. "의식 N" is Awareness N; the bracketed part says which situation the
   rotation is for. Elucidator codenames name the one in the party: ANGE is Manaka, NAVI
   Futaba. VINO is kept as lufel writes it (no source here says what it stands for). */
const LABEL_KR = [
  [/의식\s*/g, 'Awareness '],
  [/미쿠/g, 'with Miku'], [/단일/g, 'single target'], [/다중/g, 'several targets'],
  [/질풍/g, 'Wind'], [/염동/g, 'Psychokinesis'], [/여름/g, 'Summer'], [/코어/g, 'Core'],
  [/(\d)\/(\d)턴/g, 'turns $1/$2'], [/(\d)T\b/g, '$1-turn cycle'],
  [/크리티컬 확률/g, 'Crit Rate build'], [/크리티컬 효과/g, 'Crit Multiplier build'],
  // lufel's English for the same two (Miku's), in the planner's one name per stat
  [/^Critical Rate$/, 'Crit Rate build'], [/^Critical Effect$/, 'Crit Multiplier build'],
  [/관통 ×/g, 'no Pierce'], [/비약점/g, 'not a weakness'],
  [/\bANGE\b/g, 'with Manaka'], [/\bNAVI\b/g, 'with Futaba']
];
/* Skill tokens. Digits are skills 1-3, HL Highlight, TH Theurgy, ↺ an automatic use (lufel's
   own notes say so); those stay as they are and the UI spells them out. */
const TOKEN_KR = {
  '감기': 'Fatigue', '총격': 'Gunshot', '근접': 'Melee', '변신': 'Transform', '강화': 'Enhance',
  '펀치': 'Punch', '특수': 'Special', '총기': 'Gun'
};
/* Miku's songs, from her own notes: 불 Play-With-Fire, 춘 Spring Storm, H Heaven. 고 marks her
   Skill 3 and has no song of its own. */
const MIKU_SONG = { '불': ' Fire', '춘': ' Spring', 'H': ' Heaven', '고': '' };
const HANGUL = /[ㄱ-힝]/;

function unwrap(mod, varName, kr) {
  if (!mod) return null;
  const bag = mod[varName] || mod;
  return bag[kr] || (Object.keys(bag).length === 1 ? bag[Object.keys(bag)[0]] : null);
}

function main() {
  const lufelFile = process.argv[2] || 'lufel.json';
  const d = JSON.parse(fs.readFileSync(lufelFile, 'utf8'));
  if (!d.parties || !d.operations)
    throw new Error('lufel dump has no `parties`/`operations` — re-run tools/fetch-lufel-data.js after the party.js fetch was added');

  const text = fs.readFileSync(DATA_FILE, 'utf8');
  const EOL = text.includes('\r\n') ? '\r\n' : '\n';
  const at = text.indexOf(BEGIN);
  const before = at >= 0 ? text.slice(0, at) : text;
  const ctx = vm.createContext({});
  vm.runInContext(before.replace(/^(\s*)(?:const|let)\s+/gm, '$1var '), ctx);
  const chars = ctx.CHARACTERS;
  const byAlias = {}, byName = {};
  for (const c of chars) { if (c.a) byAlias[norm(c.a)] = c; byName[norm(c.n)] = c; }
  const match = info => {
    const cn = info.codename || '';
    if (EXPLICIT[cn]) return chars.find(c => c.n === EXPLICIT[cn]) || null;
    return byAlias[norm(cn)] || byName[norm(info.name_en || '')] || null;
  };

  const info = d.character_info || {};
  const rosterVar = Object.keys(info).find(k => {
    const v = info[k];
    return v && typeof v === 'object' && !Array.isArray(v) &&
           Object.values(v).some(e => e && typeof e === 'object' && 'rarity' in e && 'element' in e);
  });
  const roster = info[rosterVar] || {};
  const krToEn = {};
  for (const [kr, rinfo] of Object.entries(roster)) { const c = match(rinfo); if (c) krToEn[kr] = c; }
  const warn = new Set();
  const nameOf = kr => {
    if (!kr) return null;
    if (kr === WONDER_KR) return 'Wonder';
    const c = krToEn[kr];
    if (!c) { warn.add(`unknown character "${kr}" — left out`); return undefined; }
    return c.n;
  };

  const tr = (s, label) => {
    let out = String(s);
    for (const [re, to] of LABEL_KR) out = out.replace(re, to);
    // lufel's English labels abbreviate Awareness as "A1"; one spelling on screen
    out = out.replace(/\bA(\d)\b/g, 'Awareness $1');
    out = out.replace(/\s+/g, ' ').replace(/\(\s*/g, '(').replace(/\s*\)/g, ')').replace(/(\S)\(/g, '$1 (').trim();
    if (HANGUL.test(out)) warn.add(`untranslated ${label}: "${s}"`);
    return out;
  };
  const turn = (s, kr) => String(s).split('+').map(x => x.trim()).filter(Boolean).map(x => {
    if (TOKEN_KR[x]) return TOKEN_KR[x];
    const song = kr === '미쿠' && x.match(/^(\d)([불춘고H])$/);
    if (song) return song[1] + MIKU_SONG[song[2]];
    if (HANGUL.test(x)) warn.add(`untranslated skill token "${x}" (${kr})`);
    return x;
  }).join('+');

  const lines = [];
  let nParty = 0, nRot = 0, nPartner = 0;
  for (const c of chars) {
    const kr = Object.keys(krToEn).find(k => krToEn[k] === c);
    if (!kr) continue;
    const P = unwrap(d.parties[kr], 'recommendParty', kr) || {};
    const O = unwrap(d.operations[kr], 'operationData', kr) || {};
    const bits = [`kr:${q(kr)}`];

    const parties = [];
    for (const p of P.party || []) {
      const m = (p.members || []).map(nameOf);
      if (m.some(x => x === undefined) || m.filter(Boolean).length < 2) continue;
      const navIdx = m.findIndex(x => x && (chars.find(cc => cc.n === x) || {}).arch === 'Navigator');
      const elu = navIdx >= 0 ? m[navIdx] : null;
      // Fuuka's backup is the entry after the four; Fuuka herself may sit anywhere before it
      const backup = m.length > 4 && elu === 'Fuuka Yamagishi' ? m[4] : null;
      const front = m.slice(0, 4).filter((x, i) => i !== navIdx);
      if (navIdx < 0) warn.add(`${c.n}: a party with no Elucidator (${m.filter(Boolean).join(', ')})`);
      const f = `f:[${front.map(x => x ? q(x) : 'null').join(',')}]`;
      parties.push(`{${f}${elu ? `,e:${q(elu)}` : ''}${backup ? `,b:${q(backup)}` : ''}}`);
    }
    if (parties.length) { bits.push(`parties:[${parties.join(',')}]`); nParty += parties.length; }

    const partners = [];
    for (const fr of P.friends || []) {
      const n = nameOf(fr.name);
      if (!n) continue;
      const why = String(fr.comment_en || '').trim();
      if (!why && fr.comment) warn.add(`Korean-only partner reason: ${c.n} → ${n}`);
      partners.push(`{n:${q(n)}${fr.A != null && fr.A !== '' ? `,a:${+fr.A}` : ''}${why ? `,why:${q(why)}` : ''}}`);
    }
    if (partners.length) { bits.push(`partners:[${partners.join(',\n' + ' '.repeat(16))}]`); nPartner += partners.length; }

    const rots = [];
    const en = O.basic_en || [];
    (O.basic || []).forEach((b, i) => {
      const label = tr((en[i] && en[i].label) || b.label || '', 'rotation label');
      const awM = String(b.label || '').match(/의식\s*(\d)/);
      const aw = awM ? +awM[1] : (b.group && /^r(\d)$/.test(b.group) ? +b.group.slice(1) : null);
      let seq;
      if (Array.isArray(b.skills)) {
        seq = b.skills.map(s => String(s || '').trim());
        while (seq.length && !seq[seq.length - 1]) seq.pop();
      } else seq = String(b.value || '').split('›').map(s => s.trim()).filter(s => s !== '');
      seq = seq.map(s => (s === '-' || s === '') ? '-' : turn(s, kr));
      if (!seq.length) return;
      if (b.variant === 'miku' && !/Miku/.test(label)) warn.add(`${c.n}: a Miku variant without a Miku label`);
      rots.push(`{${aw != null ? `aw:${aw},` : ''}label:${q(label)},seq:[${seq.map(q).join(',')}]}`);
    });
    if (rots.length) { bits.push(`rot:[${rots.join(',\n' + ' '.repeat(11))}]`); nRot += rots.length; }

    const notes = (O.note_en || []).map(s => String(s).trim()).filter(Boolean);
    if (!notes.length && (O.note || []).some(s => String(s).trim()))
      warn.add(`Korean-only rotation notes skipped: ${c.n}`);
    if (notes.length) bits.push(`notes:[${notes.map(q).join(',')}]`);

    lines.push(`  ${q(c.n)}: { ${bits.join(',\n    ')} },`);
  }

  const block = [BEGIN,
    '/* lufel.net\'s recommended parties (3 thieves + Elucidator; Wonder is in every party and listed only',
    '   when a team runs him as the damage dealer; `b` is the backup Fuuka\'s Oracle Shift swaps in; null is',
    '   a free slot), synergy partners with lufel\'s reason (`a`: the Awareness the reason needs), and skill',
    '   rotations (`aw`: the Awareness level they are written for; tokens: 1-3 skills, HL Highlight,',
    '   TH Theurgy, ↺ used automatically, "-" no action). See docs/DATA-SOURCES.md. */',
    'const TEAMS = {', ...lines, '};', END].join('\n').replace(/\n/g, EOL);

  let out;
  if (at >= 0) {
    const endAt = text.indexOf(END, at);
    if (endAt < 0) throw new Error('TEAMS begin marker without an end marker in src/data.js');
    out = text.slice(0, at) + block + text.slice(endAt + END.length);
  } else {
    out = text.replace(/\s*$/, '') + EOL + EOL + block + EOL;
  }
  fs.writeFileSync(DATA_FILE, out, 'utf8');
  console.error(`TEAMS: ${lines.length} characters, ${nParty} parties, ${nPartner} partners, ${nRot} rotations`);
  for (const w of warn) console.error('  ! ' + w);
}

main();
