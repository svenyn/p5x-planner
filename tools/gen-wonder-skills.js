#!/usr/bin/env node
/* Writes the WONDER_SKILLS block at the end of src/data.js from lufel.net's Persona skill list
 * (/data/kr/wonder/skills.js): every skill a Persona can have, by English name, with its kind and the
 * values it prints at skill levels 6, 7 and 8. The Personas tab offers these as skill cards and fused
 * skills (any skill, priced or not, since an unpriced skill still takes one of a Persona's six slots),
 * and a priced skill's numbers follow its Persona's skill level through `sv`.
 *
 *     node tools/gen-wonder-skills.js             # downloads lufel's skills.js
 *     node tools/gen-wonder-skills.js skills.js   # or reads a saved copy
 *
 * Like gen-bosses.js it touches nothing else in the file: the block sits between two marker comments,
 * is replaced whole on a re-run (a second run is byte-identical), and is appended when the markers are
 * absent.
 *
 * How lufel's file is read:
 *   type         공격 attack, 지원 support, 회복 heal, 패시브 passive
 *   description  the Korean text; an active skill prints each number that grows as "a/b/c", levels 6/7/8,
 *                which becomes sv: { c: [a, b, c] }, the top value being the one WONDER_BUFFS prices. A
 *                passive is ranked by name instead (Attack Boost I ... V) and grows with nothing, so it has
 *                no sv. A number two places give different ladders is left out (not scaled).
 * lufel also lists each ranked passive once more under its bare name with every rank's value
 * ("Attack Boost: 5.8%/8.3%/..."); that summary is not a skill a Persona has and is left out.
 * A name lufel lists twice (Maeigaon, Tempest Slash, ...) is one skill here.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const DATA_FILE = path.join(ROOT, 'src', 'data.js');
const BEGIN = '/* ---- WONDER_SKILLS: generated by tools/gen-wonder-skills.js from lufel.net wonder/skills.js — do not edit by hand ---- */';
const END = '/* ---- end WONDER_SKILLS ---- */';
const URL = 'https://lufel.net/data/kr/wonder/skills.js';
const q = s => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const TYPE = { '공격': 'attack', '지원': 'support', '회복': 'heal', '패시브': 'passive' };

async function main() {
  const src = process.argv[2] ? fs.readFileSync(process.argv[2], 'utf8')
    : await (await fetch(URL, { headers: { 'User-Agent': 'p5x-planner/1.0' } })).text();
  const ctx = { window: {} };
  vm.createContext(ctx);
  vm.runInContext(src, ctx);
  const list = ctx.window.personaSkillList;
  if (!list) throw new Error('no personaSkillList in lufel skills.js');

  const warn = [];
  const out = new Map();
  Object.entries(list).forEach(([kr, s]) => {
    const n = String(s.name_en || '').trim();
    if (!n) { warn.push('no English name: ' + kr); return; }
    const t = TYPE[s.type];
    if (!t) warn.push(`${n}: unknown type ${s.type}`);
    const e = out.get(n) || { t: t || 'passive', sv: {} };
    if (t && e.t !== t) warn.push(`${n}: listed twice with types ${e.t} and ${t}`);
    if (t !== 'passive') {
      // a whole "a/b/c" run; one of any other length is not levels 6/7/8
      for (const m of String(s.description || '').matchAll(/\d+(?:\.\d+)?%?(?:\/\d+(?:\.\d+)?%?)+/g)) {
        const arr = m[0].split('/').map(x => parseFloat(x));
        if (arr.length !== 3) continue;
        const k = String(arr[2]);
        if (e.sv[k] === false) continue;
        if (k in e.sv && JSON.stringify(e.sv[k]) !== JSON.stringify(arr)) e.sv[k] = false; else e.sv[k] = arr;
      }
    }
    out.set(n, e);
  });
  // a ranked passive's summary entry: a bare name whose ranks ("<name> I", "<name> II", ...) are listed too
  const ROMAN = /\s(I|II|III|IV|V|VI)$/;
  const ranked = new Set([...out.keys()].filter(n => ROMAN.test(n)).map(n => n.replace(ROMAN, '')));
  const summaries = [...out.keys()].filter(n => !ROMAN.test(n) && ranked.has(n));
  summaries.forEach(n => out.delete(n));

  const obj = o => '{ ' + Object.entries(o).filter(([, a]) => a && a.some(x => x !== a[a.length - 1]))
    .map(([k, a]) => `${q(k)}: [${a.join(', ')}]`).join(', ') + ' }';
  const rows = [...out.entries()].sort((a, b) => a[0].localeCompare(b[0]));
  const lines = rows.map(([n, e]) => {
    const sv = obj(e.sv);
    return `  ${q(n)}: { t: ${q(e.t)}${sv === '{  }' ? '' : ', sv: ' + sv} },`;
  });
  lines[lines.length - 1] = lines[lines.length - 1].replace(/,$/, '');

  const text = fs.readFileSync(DATA_FILE, 'utf8');
  const EOL = text.includes('\r\n') ? '\r\n' : '\n';
  const block = [BEGIN,
    '/* Every Persona skill lufel lists, by English name: its kind (t: attack, support, heal, passive) and, for an',
    '   active skill, each number it prints at skill levels 6/7/8 (sv: top value -> the three). The Personas tab',
    '   offers all of them as skill cards and fused skills; see personaSkillLines in logic.js and the comment in',
    '   tools/gen-wonder-skills.js. */',
    'const WONDER_SKILLS = {', ...lines, '};', END].join('\n').replace(/\n/g, EOL);
  const at = text.indexOf(BEGIN);
  let res;
  if (at >= 0) {
    const endAt = text.indexOf(END, at);
    if (endAt < 0) throw new Error('WONDER_SKILLS begin marker without an end marker in src/data.js');
    res = text.slice(0, at) + block + text.slice(endAt + END.length);
  } else res = text.replace(/\s*$/, '') + EOL + EOL + block + EOL;
  fs.writeFileSync(DATA_FILE, res, 'utf8');
  warn.forEach(w => console.error('WONDER_SKILLS: ' + w));
  console.error(`WONDER_SKILLS: ${rows.length} skills (${rows.filter(([, e]) => e.t === 'passive').length} passive), ` +
    `${rows.reduce((a, [, e]) => a + Object.values(e.sv).filter(Boolean).length, 0)} skill-level ladders; ${summaries.length} rank summaries left out`);
}

main();
