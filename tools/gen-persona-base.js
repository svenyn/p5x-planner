#!/usr/bin/env node
/* Writes the PERSONA_BASE block at the end of src/data.js: each Persona's HP, Attack and Defense at
 * level 1, from Game8's Persona pages ("Base Level Stats"). lufel publishes no Persona stats at all;
 * Game8 does, at level 1 only. The user's own screen matched Game8 exactly for Black Frost (229 / 84 /
 * 42 at level 1, 10 Nov 2026). The page works a Persona's stats at its level out from these
 * (personaStatCalc in logic.js; the rule and the readings it was fitted on are in docs/DATA-SOURCES.md,
 * "Persona stats by level").
 *
 *     node tools/gen-persona-base.js            # downloads Game8's Persona list and every Persona page
 *     node tools/gen-persona-base.js <folder>   # caches the pages there, and reads them from it next time
 *
 * Like gen-bosses.js it touches nothing else in the file: the block sits between two marker comments,
 * is replaced whole on a re-run (a second run is byte-identical), and is appended when the markers are
 * absent. Names are matched to lufel's English names (WONDER_PERSONA's keys) ignoring case, accents,
 * spaces and punctuation, then through NAME_FIX; a Persona with no Game8 page, or one whose page lists no
 * base stats, is reported on stderr and left out (the page then asks for its stats by hand).
 * One request a second: it is someone else's site.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const DATA_FILE = path.join(ROOT, 'src', 'data.js');
const BEGIN = '/* ---- PERSONA_BASE: generated by tools/gen-persona-base.js from Game8 Persona pages — do not edit by hand ---- */';
const END = '/* ---- end PERSONA_BASE ---- */';
const LIST = 'https://game8.co/games/Persona-5-Phantom-X/archives/531191';
const q = s => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
// Game8 name -> lufel's, where the two spell it differently
// ("Jack-o" is the alt text cut at its apostrophe)
const NAME_FIX = { 'Shiisa': 'Shiisaa', 'Nian Shou': 'Nian', 'Jack-o': "Jack-o'-Lantern" };

const key = s => String(s).normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]/g, '');
const sleep = ms => new Promise(r => setTimeout(r, ms));

async function get(url, cacheDir) {
  const file = cacheDir ? path.join(cacheDir, url.replace(/\D+/g, '_').replace(/^_|_$/g, '') + '.html') : null;
  if (file && fs.existsSync(file)) return fs.readFileSync(file, 'utf8');
  await sleep(1000);
  const r = await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0 (p5x-planner data refresh)' } });
  if (!r.ok) throw new Error(r.status + ' ' + url);
  const t = await r.text();
  if (file) fs.writeFileSync(file, t, 'utf8');
  return t;
}

// the Persona names lufel knows, from the WONDER_PERSONA block in src/data.js
function lufelNames(text) {
  const at = text.indexOf('const WONDER_PERSONA = {');
  if (at < 0) throw new Error('no WONDER_PERSONA in src/data.js; run tools/gen-wonder-innate.js first');
  let depth = 0, i = text.indexOf('{', at);
  const start = i;
  for (; i < text.length; i++) { if (text[i] === '{') depth++; else if (text[i] === '}' && --depth === 0) break; }
  const ctx = vm.createContext({});
  vm.runInContext('var W = ' + text.slice(start, i + 1), ctx);
  return Object.keys(ctx.W);
}

async function main() {
  const cacheDir = process.argv[2] || null;
  if (cacheDir) fs.mkdirSync(cacheDir, { recursive: true });
  const text = fs.readFileSync(DATA_FILE, 'utf8');
  const names = lufelNames(text), byKey = new Map(names.map(n => [key(n), n]));

  // the list page's table: an unquoted href to the Persona's page, then its picture with the name as alt text
  const list = await get(LIST, cacheDir);
  const pages = new Map();
  for (const m of list.matchAll(/href=['"]?(https:\/\/game8\.co\/games\/Persona-5-Phantom-X\/archives\/\d+)['"]?\s*>\s*<img[^>]*?alt='([^']+)'/g)) {
    const n = m[2].trim();
    if (!pages.has(n)) pages.set(n, m[1]);
  }
  const rows = new Map(), warn = [];
  for (const [g8, url] of pages) {
    const ours = NAME_FIX[g8] || byKey.get(key(g8));
    // the list also links its skill pages (Agi, Attack Boost IV, ...), so a name lufel lacks is not reported
    if (!ours) continue;
    if (rows.has(ours)) continue;
    let page;
    try { page = await get(url, cacheDir); } catch (e) { warn.push(`${ours}: ${e.message}`); continue; }
    const at = page.indexOf('Base Level Stats');
    const flat = at < 0 ? '' : page.slice(at, at + 1500).replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ');
    const m = flat.match(/^Base Level Stats HP Attack Defense (\d+) (\d+) (\d+)/);
    if (!m) { warn.push(`${ours}: no base stats on its Game8 page (${url})`); continue; }
    rows.set(ours, [+m[1], +m[2], +m[3]]);
  }
  const missing = names.filter(n => !rows.has(n));
  const lines = [...rows].sort((a, b) => a[0].localeCompare(b[0])).map(([n, v]) => `  ${q(n)}: [${v.join(', ')}],`);
  if (lines.length) lines[lines.length - 1] = lines[lines.length - 1].replace(/,$/, '');

  const EOL = text.includes('\r\n') ? '\r\n' : '\n';
  const block = [BEGIN,
    '/* Each Persona\'s [HP, Attack, Defense] at level 1, from Game8\'s Persona pages ("Base Level Stats"). A Persona',
    '   missing here has no such numbers on Game8; the Personas tab then asks for its stats from the game. See',
    '   tools/gen-persona-base.js. */',
    'const PERSONA_BASE = {', ...lines, '};', END].join('\n').replace(/\n/g, EOL);
  const at = text.indexOf(BEGIN);
  let out;
  if (at >= 0) {
    const endAt = text.indexOf(END, at);
    if (endAt < 0) throw new Error('PERSONA_BASE begin marker without an end marker in src/data.js');
    out = text.slice(0, at) + block + text.slice(endAt + END.length);
  } else out = text.replace(/\s*$/, '') + EOL + EOL + block + EOL;
  fs.writeFileSync(DATA_FILE, out, 'utf8');
  console.error(`PERSONA_BASE: ${rows.size} of ${names.length} Personas (${pages.size} on Game8's list)`);
  for (const w of warn) console.error('  ! ' + w);
  if (missing.length) console.error(`  not on Game8 with base stats: ${missing.join(', ')}`);
}
main().catch(e => { console.error(e); process.exit(1); });
