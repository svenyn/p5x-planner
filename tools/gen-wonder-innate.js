#!/usr/bin/env node
/* Writes the WONDER_INNATE block at the end of src/data.js from lufel.net's Persona files: each
   Persona's innate skills (the ones it learns as it levels), by English name. The Teams tab prices
   an innate skill as the skill card of the same name (WONDER_BUFFS.cards in logic.js), cast while
   that Persona is the one in use; a name with no priced card does nothing for a teammate's damage.

       node tools/gen-wonder-innate.js            # downloads lufel's index and the 155 Persona files
       node tools/gen-wonder-innate.js <folder>   # or reads a saved index.js and <Korean name>.js files

   Like gen-bosses.js it touches nothing else in the file: the block sits between two marker
   comments, is replaced whole on a re-run (a second run is byte-identical), and is appended when
   the markers are absent. Personas are keyed by lufel's English name, as WONDER_BUFFS is. */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const DATA_FILE = path.join(ROOT, 'src', 'data.js');
const BEGIN = '/* ---- WONDER_INNATE: generated by tools/gen-wonder-innate.js from lufel.net persona files — do not edit by hand ---- */';
const END = '/* ---- end WONDER_INNATE ---- */';
const BASE = 'https://lufel.net/';
const q = s => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const get = async u => {
  const r = await fetch(u, { headers: { 'User-Agent': 'p5x-planner/1.0' } });
  if (!r.ok) throw new Error(r.status + ' ' + u);
  return r.text();
};

async function main() {
  const dir = process.argv[2];
  const ctx = { window: {} };
  vm.createContext(ctx);
  const read = async (name, sub) => dir ? fs.readFileSync(path.join(dir, name.replace(/[\\/:*?"<>|]/g, '_') + '.js'), 'utf8')
    : get(BASE + (sub || 'data/persona') + '/' + encodeURIComponent(name) + '.js');
  vm.runInContext(await read('index', 'data/persona'), ctx);
  const index = ctx.window.personaIndex;
  if (!index) throw new Error('no personaIndex in lufel index.js');
  for (const [name, e] of Object.entries(index)) vm.runInContext(await read(name, e.__path), ctx);
  const files = ctx.window.personaFiles || {};

  const rows = Object.values(files)
    .map(p => [String(p.name_en || '').trim(), [...new Set((p.innate_skill || []).map(s => String(s.name_en || '').trim()).filter(Boolean))]])
    .filter(([n, l]) => n && l.length)
    .sort((a, b) => a[0].localeCompare(b[0]));
  const lines = rows.map(([n, l]) => `  ${q(n)}: [${l.map(q).join(', ')}],`);
  lines[lines.length - 1] = lines[lines.length - 1].replace(/,$/, '');

  const text = fs.readFileSync(DATA_FILE, 'utf8');
  const EOL = text.includes('\r\n') ? '\r\n' : '\n';
  const block = [BEGIN,
    '/* Each Persona\'s innate skills by English name (lufel\'s Persona files). The Teams tab prices one as',
    '   the skill card of the same name, cast while that Persona is in use. See tools/gen-wonder-innate.js. */',
    'const WONDER_INNATE = {', ...lines, '};', END].join('\n').replace(/\n/g, EOL);
  const at = text.indexOf(BEGIN);
  let out;
  if (at >= 0) {
    const endAt = text.indexOf(END, at);
    if (endAt < 0) throw new Error('WONDER_INNATE begin marker without an end marker in src/data.js');
    out = text.slice(0, at) + block + text.slice(endAt + END.length);
  } else out = text.replace(/\s*$/, '') + EOL + EOL + block + EOL;
  fs.writeFileSync(DATA_FILE, out, 'utf8');
  console.error(`WONDER_INNATE: ${rows.length} Personas, ${rows.reduce((a, [, l]) => a + l.length, 0)} innate skills`);
}

main();
