#!/usr/bin/env node
/* Writes the WONDER_INNATE block at the end of src/data.js from lufel.net's Persona files: each
   Persona's innate skills (the ones it learns as it levels), by English name. The Teams tab prices
   an innate skill as the skill card of the same name (WONDER_BUFFS.cards in logic.js), cast while
   that Persona is the one in use; a name with no priced card does nothing for a teammate's damage.

       node tools/gen-wonder-innate.js            # downloads lufel's index and the 155 Persona files
       node tools/gen-wonder-innate.js <folder>   # or reads a saved index.js and <Korean name>.js files

   Like gen-bosses.js it touches nothing else in the file: the block sits between two marker
   comments, is replaced whole on a re-run (a second run is byte-identical), and is appended when
   the markers are absent. Personas are keyed by lufel's English name, as WONDER_BUFFS is.

   It also writes WONDER_PERSONA, what the page's Personas tab records and what changes a Persona's
   numbers (see the comment above it below).

   The same block lists the Personas Global does not have yet (WONDER_UNRELEASED), which the Teams
   tab never offers or prices. lufel shows every Persona whatever the server, so this reads its
   GLB/JP release schedule (/apps/schedule/data.js; schedule.js in <folder>), the one the roster
   order and the Space-card pairings already come from: a Persona the schedule releases in a version
   after the last one dated on or before today is not out yet. An undated version before a dated one
   is out (Sraosha's 3.4). A Persona the schedule never names shipped before it began, at launch.
   Like the pairings, this is decided when the generator runs: re-run it after a release. */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const DATA_FILE = path.join(ROOT, 'src', 'data.js');
const BEGIN = '/* ---- WONDER_INNATE: generated by tools/gen-wonder-innate.js from lufel.net persona files — do not edit by hand ---- */';
const END = '/* ---- end WONDER_INNATE ---- */';
const BASE = 'https://lufel.net/';
const q = s => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const get = async u => {
  const r = await fetch(u, { headers: { 'User-Agent': 'p5x-planner/1.0' } });
  if (!r.ok) throw new Error(r.status + ' ' + u);
  return r.text();
};

async function main() {
  const dir = process.argv[2];
  const ctx = { window: {} };
  vm.createContext(ctx);
  const read = async (name, sub) => dir ? fs.readFileSync(path.join(dir, name.replace(/[\\/:*?"<>|]/g, '_') + '.js'), 'utf8')
    : get(BASE + (sub || 'data/persona') + '/' + encodeURIComponent(name) + '.js');
  vm.runInContext(await read('index', 'data/persona'), ctx);
  const index = ctx.window.personaIndex;
  if (!index) throw new Error('no personaIndex in lufel index.js');
  for (const [name, e] of Object.entries(index)) vm.runInContext(await read(name, e.__path), ctx);
  const files = ctx.window.personaFiles || {};

  const rows = Object.values(files)
    .map(p => [String(p.name_en || '').trim(), [...new Set((p.innate_skill || []).map(s => String(s.name_en || '').trim()).filter(Boolean))]])
    .filter(([n, l]) => n && l.length)
    .sort((a, b) => a[0].localeCompare(b[0]));
  const lines = rows.map(([n, l]) => `  ${q(n)}: [${l.map(q).join(', ')}],`);
  lines[lines.length - 1] = lines[lines.length - 1].replace(/,$/, '');

  /* WONDER_PERSONA: what the Personas section of the page records and what changes a Persona's numbers.
     Per Persona: rarity, element, its talent ranks (lufel lists the talent once per rank: the base, then
     I, II, ...), the level each innate skill is learned at, and two tables that turn a top-rank value —
     the one WONDER_BUFFS prices — into the value at a lower rank:
       tv  talent rank: a number in the top rank's talent text -> its value at each rank. Ranks are lined
           up sentence by sentence (the same sentence with its numbers blanked out), so a clause a rank
           adds (Janosik's Hunting III) reads null below it: not there yet. A reworded sentence still
           holding the number keeps it; one that no longer holds it keeps the rank below's value.
       sv  skill level: a value lufel prints as "a/b/c" in the unique skill, Highlight or an innate skill
           (levels 6, 7 and 8) -> the three.
     Only numbers that change are kept, and a number two places give different ladders is left out (not
     scaled). Read from the Korean text, which prints every rank. */
  const ELEM = { '화염': 'Fire', '빙결': 'Ice', '전격': 'Electric', '질풍': 'Wind', '염동': 'Psychokinesis', '핵열': 'Nuclear',
    '축복': 'Bless', '주원': 'Curse', '만능': 'Almighty', '물리': 'Physical', '총격': 'Gun' };
  const NUM = /\d+(?:\.\d+)?/g;
  // a sentence ends at a full stop that is not a decimal point
  const sents = t => String(t || '').split(/\n|(?<=[^\d][.。])\s*/).map(x => x.trim()).filter(Boolean)
    .map(x => ({ shape: x.replace(NUM, '#'), nums: (x.match(NUM) || []).map(Number) }));
  const ladder = (out, k, arr) => {
    if (out[k] === false) return;
    if (k in out && JSON.stringify(out[k]) !== JSON.stringify(arr)) out[k] = false; else out[k] = arr;
  };
  const tidy = o => Object.fromEntries(Object.entries(o).filter(([, a]) => a && a.some(x => x !== a[a.length - 1])));
  const ROMAN = /\s(I|II|III|IV|V)$/;
  const pRows = Object.values(files).map(p => {
    const n = String(p.name_en || '').trim();
    const ranks = (p.passive_skill || []).map(r => sents(r.desc));
    const tv = {};
    if (ranks.length > 1) ranks[ranks.length - 1].forEach(S => S.nums.forEach((v, j) => {
      let seen = false, last = null;
      // no sentence of that shape, but the number itself is in the rank's text: the clause is there, reworded
      // (Janosik's "+20% ATK on a Marked foe", merged into one sentence with crit at IV)
      const arr = ranks.map(R => {
        const m = R.find(x => x.shape === S.shape);
        if (m) { seen = true; last = m.nums[j]; return last; }
        if (R.some(x => x.nums.includes(v))) { seen = true; last = v; return v; }
        return seen ? last : null;
      });
      ladder(tv, String(v), arr);
    }));
    const sv = {};
    [p.uniqueSkill, p.highlight, ...(p.innate_skill || [])].forEach(s => {
      for (const m of String((s && s.desc) || '').matchAll(/(\d+(?:\.\d+)?)%?\/(\d+(?:\.\d+)?)%?\/(\d+(?:\.\d+)?)/g))
        ladder(sv, String(+m[3]), [+m[1], +m[2], +m[3]]);
    });
    const learn = {};
    (p.innate_skill || []).forEach(s => { const k = String(s.name_en || '').trim(); if (k && !(k in learn)) learn[k] = +s.learn_level || 1; });
    const el = String(p.element || '');
    if (el && !ELEM[el]) console.error(`WONDER_PERSONA: ${n}: element ${el} has no English name here`);
    return [n, { r: +p.star || 0, e: ELEM[el] || el, t: (p.passive_skill || []).map(r => (String(r.name_en || '').match(ROMAN) || ['', ''])[1]),
      learn, tv: tidy(tv), sv: tidy(sv) }];
  }).filter(([n]) => n).sort((a, b) => a[0].localeCompare(b[0]));
  const obj = o => '{ ' + Object.entries(o).map(([k, v]) => `${q(k)}: ${Array.isArray(v) ? '[' + v.map(x => x == null ? 'null' : x).join(', ') + ']' : v}`).join(', ') + ' }';
  const pLines = pRows.map(([n, d]) => `  ${q(n)}: { r: ${d.r}, e: ${q(d.e)}, t: [${d.t.map(q).join(', ')}], learn: ${obj(d.learn)}, tv: ${obj(d.tv)}, sv: ${obj(d.sv)} },`);
  pLines[pLines.length - 1] = pLines[pLines.length - 1].replace(/,$/, '');

  vm.runInContext(dir ? fs.readFileSync(path.join(dir, 'schedule.js'), 'utf8') : await get(BASE + 'apps/schedule/data.js'), ctx);
  const sched = ctx.window.ReleaseScheduleData;
  if (!sched) throw new Error('no ReleaseScheduleData in lufel schedule data.js');
  const versions = [...(sched.manualReleases || []), ...(sched.autoGenerateCharacters || [])];
  const today = new Date().toISOString().slice(0, 10);
  let lastOut = -1;
  versions.forEach((v, i) => { if (v.date && v.date <= today) lastOut = i; });
  const enOf = kr => (files[kr] && String(files[kr].name_en || '').trim()) || (index[kr] && index[kr].name_en);
  const later = [];
  versions.forEach((v, i) => {
    for (const kr of v.persona || []) {
      const en = enOf(kr);
      if (!en) throw new Error(`schedule names a Persona lufel has no file for: ${kr}`);
      if (i > lastOut) later.push([en, v.version, v.date || null]);
    }
  });
  const unrel = later.map(([n, ver, d]) => `  ${q(n)}, // ${ver}${d ? ', ' + d : ', not dated yet'}`);

  const text = fs.readFileSync(DATA_FILE, 'utf8');
  const EOL = text.includes('\r\n') ? '\r\n' : '\n';
  const block = [BEGIN,
    '/* Each Persona\'s innate skills by English name (lufel\'s Persona files). The Teams tab prices one as',
    '   the skill card of the same name, cast while that Persona is in use. See tools/gen-wonder-innate.js. */',
    'const WONDER_INNATE = {', ...lines, '};',
    `/* Personas lufel's GLB schedule has not released yet, as of ${today}: never offered or priced on the`,
    '   Teams tab. Re-run tools/gen-wonder-innate.js after a release. */',
    'const WONDER_UNRELEASED = [', ...unrel, '];',
    '/* Every Persona lufel lists: rarity (r), element (e), talent ranks (t: "" for the base, then I, II, ...),',
    '   the level each innate skill is learned at, and the value of a top-rank number at each talent rank (tv)',
    '   and skill level 6/7/8 (sv). The Personas section records which you own and at what rank; see',
    '   personaLines in logic.js and the comment in tools/gen-wonder-innate.js. */',
    'const WONDER_PERSONA = {', ...pLines, '};', END].join('\n').replace(/\n/g, EOL);
  const at = text.indexOf(BEGIN);
  let out;
  if (at >= 0) {
    const endAt = text.indexOf(END, at);
    if (endAt < 0) throw new Error('WONDER_INNATE begin marker without an end marker in src/data.js');
    out = text.slice(0, at) + block + text.slice(endAt + END.length);
  } else out = text.replace(/\s*$/, '') + EOL + EOL + block + EOL;
  fs.writeFileSync(DATA_FILE, out, 'utf8');
  console.error(`WONDER_INNATE: ${rows.length} Personas, ${rows.reduce((a, [, l]) => a + l.length, 0)} innate skills`);
  console.error(`WONDER_PERSONA: ${pRows.length} Personas, ${pRows.reduce((a, [, d]) => a + Object.keys(d.tv).length, 0)} talent ladders, ${pRows.reduce((a, [, d]) => a + Object.keys(d.sv).length, 0)} skill-level ladders`);
  console.error(`WONDER_UNRELEASED: ${later.map(([n, ver]) => `${n} (${ver})`).join(', ') || 'none'}`);
}

main();
