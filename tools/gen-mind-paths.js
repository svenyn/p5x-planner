#!/usr/bin/env node
/* Writes the MIND_SKILL_PATHS block in src/data.js from lufel.net's per-character setting.js:
 * which skills each of the two Mindscape skill paths raises (lufel's `mind_skill1` / `mind_skill2`,
 * shown on a character's page under Mindscape at level 5 as "skill enforce 1" and "2").
 *
 *     node tools/fetch-lufel-data.js lufel.json
 *     node tools/gen-mind-paths.js lufel.json
 *
 * lufel writes a path as the skills it raises, "S1/S2", "S3/HL", "S2/S3/추격", with "!" on a path its
 * build says to level and "×" on one it says to skip; neither mark changes what the path raises, so
 * both are dropped. TH (a Theurgy) is written HL, the slot it takes; 추격 (a follow-up) is `fu`. "-",
 * or no entry, is a character lufel has not filled in: they get no row, and the planner then reads
 * both paths as raising every skill at their mean level. Names are matched through TEAMS' `kr`,
 * so run tools/gen-teams.js first after a roster refresh. A second run is byte-identical.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const DATA_FILE = path.join(ROOT, 'src', 'data.js');
const BEGIN = '/* ---- MIND_SKILL_PATHS: generated by tools/gen-mind-paths.js from lufel.net setting.js — do not edit by hand ---- */';
const END = '/* ---- end MIND_SKILL_PATHS ---- */';
const SKILL = { S1: '1', S2: '2', S3: '3', HL: 'HL', TH: 'HL', '추격': 'fu' };

function parsePath(s) {
  if (s == null) return null;
  const t = String(s).replace(/[!×xX]/g, '').trim();
  if (!t || t === '-') return null;
  const out = [];
  for (const part of t.split('/').map(p => p.trim()).filter(Boolean)) {
    const k = SKILL[part] || SKILL['S' + part];
    if (!k) throw new Error(`unknown Mindscape skill "${part}" in "${s}"`);
    if (!out.includes(k)) out.push(k);
  }
  return out.length ? out : null;
}

function main() {
  const d = JSON.parse(fs.readFileSync(process.argv[2] || 'lufel.json', 'utf8'));
  if (!d.settings) throw new Error('lufel dump has no `settings` — re-run tools/fetch-lufel-data.js');
  const text = fs.readFileSync(DATA_FILE, 'utf8');
  const EOL = text.includes('\r\n') ? '\r\n' : '\n';
  const at = text.indexOf(BEGIN);
  const src = at >= 0 ? text.slice(0, at) + text.slice(text.indexOf(END, at) + END.length) : text;
  const ctx = vm.createContext({});
  vm.runInContext(src.replace(/^(\s*)(?:const|let)\s+/gm, '$1var '), ctx);
  const krToEn = {};
  for (const [n, t] of Object.entries(ctx.TEAMS || {})) if (t && t.kr) krToEn[t.kr] = n;
  const rows = [], none = [];
  for (const c of ctx.CHARACTERS) {
    const kr = Object.keys(krToEn).find(k => krToEn[k] === c.n);
    const bag = kr && d.settings[kr];
    const s = bag && ((bag.characterSetting || {})[kr] || bag[kr] || bag);
    const p1 = parsePath(s && s.mind_skill1), p2 = parsePath(s && s.mind_skill2);
    if (!p1 && !p2) { none.push(c.n); continue; }
    const q = a => '[' + (a || []).map(k => `'${k}'`).join(', ') + ']';
    rows.push(`  ${JSON.stringify(c.n).replace(/"/g, "'")}: [${q(p1)}, ${q(p2)}],`);
  }
  const block = [BEGIN,
    '/* Which skills each Mindscape skill path raises, path 1 then path 2 (lufel\'s mind_skill1/2). Each level of',
    '   a path is one skill level on each skill it lists. A character with no row: lufel has not filled it in. */',
    'const MIND_SKILL_PATHS = {', ...rows, '};', END].join('\n').replace(/\n/g, EOL);
  let out;
  if (at >= 0) out = text.slice(0, at) + block + text.slice(text.indexOf(END, at) + END.length);
  else {
    const tEnd = text.indexOf('/* ---- end TEAMS ---- */');
    if (tEnd < 0) throw new Error('no TEAMS block in src/data.js to place MIND_SKILL_PATHS after');
    const cut = tEnd + '/* ---- end TEAMS ---- */'.length;
    out = text.slice(0, cut) + EOL + EOL + block + text.slice(cut);
  }
  fs.writeFileSync(DATA_FILE, out);
  console.error(`MIND_SKILL_PATHS: ${rows.length} characters; none on lufel for ${none.length}: ${none.join(', ')}`);
}
main();
