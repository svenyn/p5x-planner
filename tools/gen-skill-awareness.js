#!/usr/bin/env node
/* Writes the SKILL_LEVEL_AW block in src/data.js from lufel.net's per-character ritual.js and skill.js: at which
 * Awareness level each skill gets its skill-level increase.
 *
 *     node tools/fetch-lufel-data.js lufel.json
 *     node tools/gen-skill-awareness.js lufel.json
 *
 * Every thief's Awareness 3 and 5 each raise two skills' levels ("Increase the skill levels of Diving Ray and
 * Blunt Edge by 2."), and between them they raise Skills 1-3 and "Thief Tactics" once each. Thief Tactics is the
 * Highlight: the S.E.E.S. members whose Theurgy replaces it say "Combat Tactics", and Elucidators, who have no
 * Highlight, list only their three skills. lufel prints a skill's numbers at its base level and after that
 * increase, so the planner reads the higher column for a skill only once its own node is reached (`tierVal`);
 * before Nov 2026 every skill switched at one Awareness level per character.
 *
 * Read from lufel's English text, which is Global's; levels are its r0-r6 keys. lufel's Korean text sometimes
 * puts a skill-level node on another level (Chizuko's at 2 and 4, Yaoling's A4); those are reported on stderr and
 * not used. A name that is not one of the character's skill names is assigned by elimination when exactly one
 * skill is left unraised (Aran's "Eyes of Judgment" for Eye of Condemnation) and reported; one that still
 * cannot be placed is reported and left out, and that skill keeps the old one-level rule.
 * Names are matched through TEAMS' `kr`. A second run is byte-identical.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const DATA_FILE = path.join(ROOT, 'src', 'data.js');
const BEGIN = '/* ---- SKILL_LEVEL_AW: generated by tools/gen-skill-awareness.js from lufel.net ritual.js — do not edit by hand ---- */';
const END = '/* ---- end SKILL_LEVEL_AW ---- */';
const SLOTS = ['1', '2', '3', 'HL'];
const RX = /increase (?:the )?skill levels? of (.+?)(?: by \d+)?\.?\s*$/i;

/* the skills one node names, as slots; `unknown` the names that are none of them */
function nodeSkills(text, names) {
  const m = String(text || '').trim().match(RX);
  if (!m) return null;
  let rest = ' ' + m[1].replace(/[[\]"“”]/g, '').replace(/\s+increase$/i, '') + ' ';
  const slots = [];
  // longest names first, so "Moonlit Scalpel / Midnight Surgery" goes before a shorter one inside it
  const known = Object.entries(names).sort((a, b) => b[0].length - a[0].length);
  for (const [nm, slot] of known) {
    const i = rest.toLowerCase().indexOf(nm.toLowerCase());
    if (i < 0) continue;
    if (!slots.includes(slot)) slots.push(slot);
    rest = rest.slice(0, i) + ' , ' + rest.slice(i + nm.length);
  }
  const sel = /selected skill (\d)/ig;
  let s;
  while ((s = sel.exec(rest))) { if (!slots.includes(s[1])) slots.push(s[1]); }
  rest = rest.replace(sel, ' , ');
  const unknown = rest.split(/,|\band\b/).map(x => x.trim()).filter(Boolean);
  return { slots, unknown };
}

function main() {
  const d = JSON.parse(fs.readFileSync(process.argv[2] || 'lufel.json', 'utf8'));
  if (!d.rituals || !d.skills) throw new Error('lufel dump has no `rituals`/`skills` — re-run tools/fetch-lufel-data.js');
  const text = fs.readFileSync(DATA_FILE, 'utf8');
  const EOL = text.includes('\r\n') ? '\r\n' : '\n';
  const at = text.indexOf(BEGIN);
  const src = at >= 0 ? text.slice(0, at) + text.slice(text.indexOf(END, at) + END.length) : text;
  const ctx = vm.createContext({});
  vm.runInContext(src.replace(/^(\s*)(?:const|let)\s+/gm, '$1var '), ctx);
  const krToEn = {};
  for (const [n, t] of Object.entries(ctx.TEAMS || {})) if (t && t.kr) krToEn[t.kr] = n;
  const rows = [], notes = [], none = [], koDiff = [];
  for (const c of ctx.CHARACTERS) {
    const kr = Object.keys(krToEn).find(k => krToEn[k] === c.n);
    const en = kr && ((d.rituals[kr] || {}).enCharacterRitualData || {})[kr];
    const sk = kr && ((d.skills[kr] || {}).enCharacterSkillsData || {})[kr];
    if (!en || !sk) { none.push(c.n); continue; }
    const names = { 'Thief Tactics': 'HL', 'Combat Tactics': 'HL' };
    ['skill1', 'skill2', 'skill3'].forEach((k, i) => { if (sk[k] && sk[k].name) names[sk[k].name.trim()] = String(i + 1); });
    const lvOf = {}, loose = [];
    for (let lv = 0; lv <= 6; lv++) {
      const r = nodeSkills(en['r' + lv + '_detail'], names);
      if (!r) continue;
      for (const s of r.slots) if (lvOf[s] == null) lvOf[s] = lv;
      for (const u of r.unknown) loose.push({ u, lv });
    }
    const has = Object.keys(lvOf).length > 0;
    // an Elucidator has no Highlight: three skills to raise, not four
    const want = sk.skill_highlight && Object.keys(sk.skill_highlight).length ? SLOTS : SLOTS.slice(0, 3);
    for (const { u, lv } of loose) {
      const left = want.filter(s => lvOf[s] == null);
      if (left.length === 1 && loose.length === 1) { lvOf[left[0]] = lv; notes.push(`${c.n}: "${u}" (A${lv}) read as ${left[0] === 'HL' ? 'the Highlight' : 'Skill ' + left[0]}, the one skill no node names`); }
      else notes.push(`${c.n}: "${u}" (A${lv}) is not one of their skills; left out`);
    }
    // lufel's Korean text, for comparison only
    const ko = ((d.rituals[kr] || {}).ritualData || {})[kr] || {};
    const koLv = [0, 1, 2, 3, 4, 5, 6].filter(lv => /스킬 레벨이/.test(ko['r' + lv + '_detail'] || ''));
    const enLv = [...new Set(Object.values(lvOf))].sort();
    if (koLv.length && koLv.join() !== enLv.join()) koDiff.push(`${c.n} (A${koLv.join('/A')})`);
    if (!has) { none.push(c.n); continue; }
    const body = SLOTS.filter(s => lvOf[s] != null).map(s => `${/^\d$/.test(s) ? `'${s}'` : s}: ${lvOf[s]}`).join(', ');
    rows.push(`  ${JSON.stringify(c.n).replace(/"/g, "'")}: { ${body} },`);
  }
  const block = [BEGIN,
    '/* The Awareness level at which each skill gets its skill-level increase (lufel\'s English Awareness text; HL is',
    '   the Highlight or Theurgy, "Thief Tactics" in the text). A skill reads lufel\'s higher column from that level on;',
    '   a skill or character with no entry keeps the one-level rule (Awareness 3, or 5 for TARGET_TIER_AWARENESS_5). */',
    'const SKILL_LEVEL_AW = {', ...rows, '};', END].join('\n').replace(/\n/g, EOL);
  let out;
  if (at >= 0) out = text.slice(0, at) + block + text.slice(text.indexOf(END, at) + END.length);
  else {
    const mEnd = text.indexOf('/* ---- end MIND_SKILL_PATHS ---- */');
    if (mEnd < 0) throw new Error('no MIND_SKILL_PATHS block in src/data.js to place SKILL_LEVEL_AW after');
    const cut = mEnd + '/* ---- end MIND_SKILL_PATHS ---- */'.length;
    out = text.slice(0, cut) + EOL + EOL + block + text.slice(cut);
  }
  fs.writeFileSync(DATA_FILE, out);
  for (const n of notes) console.error('  ' + n);
  if (koDiff.length) console.error(`  lufel's Korean text has the skill-level nodes on other levels for ${koDiff.length} (English used): ${koDiff.join(', ')}`);
  console.error(`SKILL_LEVEL_AW: ${rows.length} characters; none for ${none.length}: ${none.join(', ')}`);
}
main();
