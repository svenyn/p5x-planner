"""Reads the card level by matching the crop against known renders of it.

Tesseract cannot read this field reliably and never could. The text is small,
slanted and stylised, and the whole margin it has ever had is nine pixels: two
captures of the *same* Lv.0 card, one via Steam's screenshot key and one via a
live screen grab, differ by 9 pixels out of 6969 after thresholding — and that
is enough to turn "Lv.0" into "9". Every workaround was measured and rejected:
threshold sweeps, upscale sweeps, JPEG round-trips, a vote across three page
segmentation modes (identical results), and a Gaussian blur that produced a
*confidently wrong* answer, which is worse than failing.

But the field does not need reading. The UI renders a given level identically
every time, so this is a 26-way lookup, not OCR. Measured over 400 labelled
frames:

    two frames of the same level      0 pixels apart, every pair, exactly
    Lv.0 vs Lv.25                   365 pixels apart, every pair, exactly
    live grab vs Steam, same level     9 pixels apart

A nearest-template match therefore has a large margin where Tesseract had none.
ACCEPT_MAX is set from the closest pair of real templates, not merely from the
noise — see there. The rule that matters is that a level with no template comes
back *unknown* and goes to review, rather than being rounded into the nearest
level that does have one, which would corrupt an inventory silently.


Templates are per (crop box, pixel size). Recalibrating the level box or
changing resolution invalidates them, so the shape is stored and a mismatch
returns unknown rather than nonsense — see `usable_for`.

`build_level_templates.py` bootstraps the file from frames whose level is
already known. Everything else is learned: correcting a level in
`review_cards.py` teaches that render, so a level is unreadable at most once.
"""
import base64
import json
from pathlib import Path

import numpy as np

DEFAULT_PATH = Path(__file__).resolve().parent / "config" / "level_templates.json"

# A match must be at least this close to be believed. Capture-method noise
# measured 9px (Steam screenshot vs live grab, same card), so this is ~3x
# headroom over the only noise ever observed.
#
# The ceiling comes from the other side: the closest pair of real templates is
# levels 16 and 18 at 80px apart. A true Lv.16 render can only be *misread* as
# 18 if its noise exceeds half that, 40px — so anything at or below 25 cannot
# be confused with a neighbour at all, whatever the noise happens to be.
ACCEPT_MAX = 25
# ...and it must beat the runner-up by this much, so a crop sitting between two
# templates is refused rather than decided by a few pixels. ACCEPT_MAX + MARGIN
# has to stay under that same 80px pair, or a clean Lv.16 capture would be
# refused for being "too close to call" against 18.
MARGIN = 40


def _bits(binary_crop):
    """Bool array from an already-binarised crop. Binarisation belongs to
    panel_ocr.binarize(), so the threshold lives in exactly one place."""
    return np.asarray(binary_crop.convert("L")) > 127


class LevelTemplates:
    """One known render per level, compared by Hamming distance."""

    def __init__(self, shape=None, templates=None):
        self.shape = tuple(shape) if shape else None
        self.templates = dict(templates or {})   # {int level: bool ndarray}

    # ------------------------------ storage ------------------------------
    #
    # Packed bits in JSON rather than .npz: this sits in config/ beside
    # crop_regions.json, and a text file that `git diff` can at least see the
    # shape of beats an opaque binary blob for something regenerable.

    @classmethod
    def load(cls, path=DEFAULT_PATH):
        path = Path(path)
        if not path.exists():
            return cls()
        with open(path, "r", encoding="utf-8") as f:
            raw = json.load(f)
        shape = tuple(raw["shape"])
        n = shape[0] * shape[1]
        templates = {}
        for lv, b64 in raw["templates"].items():
            flat = np.unpackbits(np.frombuffer(base64.b64decode(b64), dtype=np.uint8))
            templates[int(lv)] = flat[:n].reshape(shape).astype(bool)
        return cls(shape, templates)

    def save(self, path=DEFAULT_PATH):
        if self.shape is None:
            raise ValueError("nothing to save: no templates have been learned")
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "shape": list(self.shape),
            "note": "Generated by build_level_templates.py and by level corrections in "
                    "review_cards.py. Tied to the level crop box in crop_regions.json at "
                    "this pixel size; recalibrating that box invalidates these.",
            "templates": {str(lv): base64.b64encode(np.packbits(t.ravel()).tobytes()).decode()
                          for lv, t in sorted(self.templates.items())},
        }
        with open(path, "w", encoding="utf-8") as f:
            json.dump(payload, f, indent=1)
        return path

    # ------------------------------ matching ------------------------------

    def __len__(self):
        return len(self.templates)

    @property
    def known(self):
        return sorted(self.templates)

    def usable_for(self, binary_crop):
        """False when there are no templates, or they were built at a different
        crop size — a recalibrated box or a resolution change."""
        return bool(self.templates) and _bits(binary_crop).shape == self.shape

    def distances(self, binary_crop):
        b = _bits(binary_crop)
        return {lv: int(np.count_nonzero(b ^ t)) for lv, t in self.templates.items()}

    def classify(self, binary_crop, accept_max=ACCEPT_MAX, margin=MARGIN):
        """Returns (level, distance, why). `level` is None when no template is
        close enough to be trusted, and `why` says which test failed so the
        caller can put something useful in the review note."""
        if not self.templates:
            return None, None, "no level templates have been built yet"
        # Shape first: distances() XORs against every template and would raise
        # on a mismatch rather than returning the refusal the caller expects.
        shape = _bits(binary_crop).shape
        if shape != self.shape:
            return None, None, (f"level templates were built for a {self.shape} crop, "
                                f"this one is {shape}")
        d = self.distances(binary_crop)
        order = sorted(d, key=lambda lv: d[lv])
        best = order[0]
        if d[best] > accept_max:
            return None, d[best], (f"closest known level is {best} at {d[best]}px, "
                                   f"past the {accept_max}px limit")
        if len(order) > 1 and d[order[1]] - d[best] < margin:
            return None, d[best], (f"levels {best} and {order[1]} are {d[best]}px and "
                                   f"{d[order[1]]}px away, too close to call")
        return best, d[best], None

    def learn(self, binary_crop, level):
        """Records this render as `level`. An exact re-teach is a no-op; a
        *different* render of a level already known replaces it, since the
        newer capture is the one that matches how frames are being taken now."""
        b = _bits(binary_crop)
        if self.shape is None:
            self.shape = b.shape
        elif b.shape != self.shape:
            raise ValueError(f"crop is {b.shape}, templates are {self.shape}")
        level = int(level)
        # bool(), not the numpy scalar np.any() hands back — this is a public
        # return value and callers compare it with `is True`.
        replaced = bool(level in self.templates and np.any(self.templates[level] ^ b))
        self.templates[level] = b
        return replaced
